'use strict';
const assert=require('node:assert/strict'),g=require('../tools/grouping.js');
const f={phash:'123456789abcdef0',dhash:'123456789abcdef0',mean_rgb:[.4,.5,.6],detail_score:.01,aspect:1,algorithm:'dct63-dhash64-rgb-v1'};
const row=(path,seconds,species='bird a',folder='A')=>({path,directory:folder,before:{sha256:path},exif:{'EXIF DateTimeOriginal':'2026:10:02 12:00:'+String(seconds).padStart(2,'0')},detection:{status:'detected'},similarity:{whole:{...f},subject:{...f}},views:[{candidates:[{label:{kind:'bird',scientific_name:species}}]}]});
const unknown={status:'unreviewed',species:[]},confirmed=id=>({status:'confirmed',species:[{scientific_name:id}]});
let rows=[row('a',0),row('b',1),row('c',2,'bird b'),row('d',3)],records=rows.map(()=>unknown);
let p=g.plan(rows,records);assert.deepEqual(p.map(x=>x.indices.length),[2,1,1]);assert.equal(p[0].folded.length,1);assert.equal(p[0].confirmed,false);
p=g.plan(rows,[confirmed('same'),confirmed('same'),confirmed('same'),confirmed('same')]);assert.equal(p.length,1);assert.equal(p[0].confirmed,true);
p=g.plan(rows,[confirmed('x'),confirmed('y'),unknown,unknown]);assert.equal(p.length,4);
p=g.plan([row('a',0),row('b',31)],[unknown,unknown]);assert.equal(p.length,2);
p=g.plan([row('a',0),row('b',1,'bird a','B')],[unknown,unknown]);assert.equal(p.length,2);
rows=[row('a',0),row('b',1),row('c',2)];records=rows.map(()=>unknown);
p=g.plan(rows,records,{keep:['b'],covers:['c']});assert.equal(p[0].cover,2);assert(p[0].visible.includes(1));assert(p[0].visible.includes(2));
assert.equal(g.plan(rows,records,{breaks:['b','c']}).length,3);
assert.equal(g.plan(rows,[unknown,{status:'uncertain',species:[]},unknown]).length,3);
const invalid=row('x',5);invalid.exif['EXIF DateTimeOriginal']='2026:02:30 12:00:00';assert.equal(g.seconds(invalid),null);
assert.equal(g.plan([rows[0],invalid],[unknown,unknown]).length,2);
assert.equal(g.similar(rows[0],row('later',20)),false);
const changed=row('change',2);changed.similarity.whole={...f,mean_rgb:[1,0,0]};assert.equal(g.similar(rows[0],changed),false);
changed.similarity.whole={...f,phash:'ffffffffffffffff'};assert.equal(g.similar(rows[0],changed),false);
changed.detection.status='no_detection';assert.equal(g.similar(rows[0],changed),false);
const chain=[row('chain-a',0),row('chain-b',8),row('chain-c',16)];
assert.equal(g.plan(chain,chain.map(()=>unknown))[0].visible.length,2,'不允许相似关系传递导致整条连拍折叠');
const multi={status:'confirmed',species:[{scientific_name:'x'},{scientific_name:'y'}]};
assert.equal(g.identity(rows[0],multi),null);
assert.throws(()=>g.plan(rows,records,{gap:0}));
const data={review_batch_id:'batch',rows};
const pref={schema:'bird-view-settings-v1',batch_id:'batch',gap:30,grouping:true,foldSimilar:true,keep:[],breaks:[],covers:[]};
assert.equal(g.validatePreferences(pref,data).gap,30);
assert.throws(()=>g.validatePreferences({...pref,keep:['missing']},data));
assert.throws(()=>g.validatePreferences({...pref,batch_id:'other'},data));
console.log('Grouping safety checks passed: folder/time/species boundaries, uncertainty, reversible keep/cover/split, non-transitive similarity, validation.');
